INSERT INTO product_prices(product_id,price_list_id,price,currency)
SELECT p.id,@general_list_id,f.sale_price,'USD'
FROM products p
JOIN catalog_fix f ON f.source_key=p.source_key
WHERE @general_list_id IS NOT NULL
ON DUPLICATE KEY UPDATE price=VALUES(price),currency='USD',updated_at=CURRENT_TIMESTAMP;

-- Recalcula automáticamente las listas derivadas (por ejemplo Gremio) desde la lista base.
INSERT INTO product_prices(product_id,price_list_id,price,currency)
SELECT bp.product_id,pl.id,ROUND(bp.price*(1-COALESCE(pl.discount_percentage,0)/100),2),'USD'
FROM price_lists pl
JOIN product_prices bp ON bp.price_list_id=pl.base_price_list_id
WHERE pl.base_price_list_id IS NOT NULL AND pl.discount_percentage IS NOT NULL
ON DUPLICATE KEY UPDATE price=VALUES(price),currency='USD',updated_at=CURRENT_TIMESTAMP;

